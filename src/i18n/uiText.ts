const localeFallback: Locale = "es";

export function getUIText(locale: Locale, key: string, fallback: string) {
  const englishFallback: Locale = "en";
  const translatedValue = uiText[locale][key];
  if (translatedValue) return translatedValue;

  if (locale === "fr" || locale === "zh") {
    return uiText[englishFallback][key] ?? uiText[localeFallback][key] ?? fallback;
  }

  return uiText[localeFallback][key] ?? fallback;
}
